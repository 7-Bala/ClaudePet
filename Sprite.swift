import Cocoa

// Clawd's artwork on a 32 x 19 grid of square cells, plus a chef hat + pan
// costume. This is a visual-correction pass on the cooking animation
// specifically — see the pixel-art generator this file's grid data was
// derived from for the full design rationale (arm/pan geometry, eye-state
// mapping, food trajectory) rather than re-deriving it here.
//
// Two structural facts that keep everything aligned:
//
// 1. Every pose starts from the same 32x19 canvas. Non-cooking poses simply
//    leave cols 20-31 blank; cooking poses use that space for the arm ->
//    handle -> pan -> food zone. Nothing ever shifts row indices between
//    poses, so switching poses can never cause a visible jump.
// 2. The cooking "toss" never sets a body offset. Every authored cooking
//    pose keeps head/body/legs pixel-identical; the only things that move
//    are the arm-hand-pan assembly (four discrete row "bands": LOW, HOLD,
//    RAISED, HIGH) and the food, which travels independently along its own
//    small ballistic arc once launched.

enum Pose {
    case standing
    case lookLeft
    case lookRight
    case armsUp
    case asleep            // eyes closed
    case walkA              // legs 1 & 3 planted
    case walkB              // legs 2 & 4 planted
    case squat               // legs folded under, for the idle sit
    case hatPlacing          // arms raised, physically putting the hat on/off
    case hatOn               // hat settled, arms back down, hands empty
    case cookHoldPan         // pan held at rest, food sitting in it, eyes on the pan
    case cookAnticipate      // wrist dips before the toss — anticipation
    case cookFlick1          // wrist rising, food still riding the pan
    case cookFlick2          // strongest flick — food launches, hat reacts
    case cookFoodLeaving     // food just separated from the pan
    case cookFoodLowAscend   // food climbing, tumbling
    case cookFoodHighAscend  // food nearing the top of the arc
    case cookFoodApex        // held: food at the peak, Claude's gaze holds too
    case cookFoodHighDescend // food falling, mirrored tumble
    case cookFoodLowDescend  // food nearly back down to pan height
    case cookCatch           // food adjacent to the pan rim
    case cookCatchDip        // pan + arm dip on impact, food merges back in
    case cookIdleEyes        // same hold as cookHoldPan, but eyes relax forward
    case terminalOn          // holding a small terminal, cursor lit — reading/researching
    case terminalOff         // same, cursor blinked off
    case typingA              // holding a small keyboard, left hand at rest
    case typingB              // same, left hand pulled in mid-keystroke
}

