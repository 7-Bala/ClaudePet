    static func grid(for pose: Pose) -> [String] {
        switch pose {
        case .standing:           return standingGrid
        case .lookLeft:           return lookLeftGrid
        case .lookRight:          return lookRightGrid
        case .armsUp:             return armsUpGrid
        case .asleep:             return asleepGrid
        case .walkA:              return walkAGrid
        case .walkB:              return walkBGrid
        case .squat:              return squatGrid
        case .hatPlacing:         return hatPlacingGrid
        case .hatOn:              return hatOnGrid
        case .cookHoldPan:        return cookHoldPanGrid
        case .cookAnticipate:     return cookAnticipateGrid
        case .cookFlick1:         return cookFlick1Grid
        case .cookFlick2:         return cookFlick2Grid
        case .cookFoodLeaving:    return cookFoodLeavingGrid
        case .cookFoodLowAscend:  return cookFoodLowAscendGrid
        case .cookFoodHighAscend: return cookFoodHighAscendGrid
        case .cookFoodApex:       return cookFoodApexGrid
        case .cookFoodHighDescend: return cookFoodHighDescendGrid
        case .cookFoodLowDescend: return cookFoodLowDescendGrid
        case .cookCatch:          return cookCatchGrid
        case .cookCatchDip:       return cookCatchDipGrid
        case .cookIdleEyes:       return cookIdleEyesGrid
        case .terminalOn:         return terminalOnGrid
        case .terminalOff:        return terminalOffGrid
        case .typingA:            return typingAGrid
        case .typingB:            return typingBGrid
        }
    }

